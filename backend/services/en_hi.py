"""Offline English -> Hindi rendering for trial titles, criteria and reasons.

The results UI and the Excel export already translated *labels* (column
headers, verdict names); this module extends coverage to the *content* itself:
trial titles, inclusion/exclusion criteria, and the rule engine's reason
strings - without depending on the frequently rate-limited Groq API.

It is deliberately a *medical domain* glossary, not general machine
translation - the mirror image of services/hi_lexicon.py (which converts
Hindi clinical notes to English for the NER). Three passes:

1. regex TEMPLATES for the sentence shapes this data actually uses (numeric
   comparisons, age ranges, durations, "history of X", "diagnosed with X") -
   these re-order numbers and direction words into natural Hindi
   postpositions ("45 से कम", "X का इतिहास");
2. multi-word PHRASES (diseases, drugs, trial-design boilerplate), longest
   first;
3. single WORDS - the remaining medical vocabulary plus a few glue words
   (and/or/not). Unmapped tokens pass through unchanged, so units (mg/dL),
   abbreviations (HbA1c, eGFR, BMI, ULN) and rare drug names survive - the
   same "Latin survives" rule hi_lexicon.py applies in reverse. Untranslated
   English glue reads as natural clinical Hinglish.
"""
