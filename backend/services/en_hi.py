# Optional unit that may follow a number ("7.5 percent", "45 mg", "6 months") -
# CAPTURED so templates can re-position it in the Hindi word order.
_UNIT_CAP = r"(years?|months?|weeks?|days?|hours?|percent|%|mg|ml|kg|mmhg|units?)?"

# Stop lookahead: capture ends at punctuation or a clause boundary word.
_STOP = (r"(?=\s*(?:[.;,]|$|\band\b|\bor\b|\bwith\b|\bwithout\b|\bwho\b|"
         r"\bwhich\b|\bthat\b|\bwhile\b|\bduring\b|\bdespite\b|\bunless\b|"
         r"\brequiring\b|\bnot\b|\bwithin\b|\bif\b))")

