# Compiled phrase patterns (longest first; hyphen == space, case-insensitive)
# ---------------------------------------------------------------------------

def _phrase_pattern(en: str) -> re.Pattern:
    words = [re.escape(w) for w in en.split()]
    return re.compile(r"(?<![A-Za-z])" + r"[\s-]+".join(words) + r"(?![A-Za-z])", re.I)


_PHRASE_RES: list[tuple[re.Pattern, str]] = [
    (_phrase_pattern(en), hi)
    for en, hi in sorted(_PHRASES.items(), key=lambda kv: -len(kv[0]))
]

# Token = letters/digits/% . / - ' (covers "HbA1c", "mg/dL", "7.5", "add-on",
# "180/110") - everything else (punctuation, spaces) is preserved as-is.
_TOKEN_RE = re.compile(r"[\w%./'’-]+", re.UNICODE)


def _word_repl(m: "re.Match") -> str:
    return _WORDS.get(m.group(0).lower(), m.group(0))


@lru_cache(maxsize=8192)
def _translate_cached(text: str) -> str:
    out = text

    # 1) sentence-shape templates
    for pat, repl in _TEMPLATES:
        out = pat.sub(repl, out)

    # 2) multi-word phrases, longest first
    for pat, hi in _PHRASE_RES:
        if pat.search(out):
            out = pat.sub(hi, out)

    # 3) single words - unknown tokens survive untouched
    out = _TOKEN_RE.sub(_word_repl, out)

    # 4) tidy spacing around punctuation introduced by the passes
    out = re.sub(r"\s*\(\s*s\s*\)", "", out)   # "2 year(s) ago" -> "2 वर्ष पहले"
    out = re.sub(r'\s+"', '"', out)
    out = re.sub(r"\s+([,.;:%])", r"\1", out)
    out = re.sub(r"([,.;:])(?=[^\s\d])", r"\1 ", out)
    out = re.sub(r"\(\s+", "(", out)
    out = re.sub(r"\s+\)", ")", out)
    out = re.sub(r"\s{2,}", " ", out)
    return out.strip()


def to_hindi(text) -> str | None:
    """Best-effort offline English→Hindi rendering of trial-domain text.

    Medical content is mapped through the glossary; numbers, units,
    abbreviations and unmapped words pass through (clinical Hinglish).
    Returns None for None/empty input so callers can fall back cleanly.
    """
    if text is None:
        return None
    text = str(text).strip()
    if not text or not any(ch.isalpha() for ch in text):
        return text or None
    return _translate_cached(text)


def to_hindi_list(items) -> list[str] | None:
    """Translate a list of criterion/reason strings (None-safe)."""
    if items is None:
        return None
    return [to_hindi(x) or (x or "") for x in items]
